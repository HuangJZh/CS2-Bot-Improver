using BotLearning;
using BotAimImprover;
using System.Numerics;
int checks=0;
void Check(bool value,string name){if(!value)throw new Exception(name);checks++;Console.WriteLine("PASS "+name);}
var memory=new RoundSpatialLearning();var hot=new Vector3(400,350,0);
memory.BeginRound();memory.Death(3,hot);
Check(memory.Risk(3,hot)==0&&memory.UtilityMultiplier(3,hot)==1,"current-round casualty does not produce immediate grenade retaliation");
Check(memory.Complete(2)&&memory.Risk(3,hot)>0,"lost defensive round creates next-round region memory");
Check(memory.UtilityMultiplier(3,hot)>1&&memory.UtilityMultiplier(3,new(3000,3000,0))<1,"utility allocation favors the failed defensive region without increasing inventory");
Check(memory.UtilityMultiplier(2,hot)==1,"defensive utility preference is not applied to the opposite side");
Check(memory.Risk(3,hot+new Vector3(0,0,128))==0,"another floor does not inherit an unrelated failure");
float before=memory.Risk(3,hot);
Check(!memory.Complete(2)&&memory.Risk(3,hot)==before,"duplicate round-end callbacks cannot double-train");
memory.BeginRound();memory.Complete(3);
Check(Math.Abs(memory.Risk(3,hot)-before*.65f)<.0001,"old failure memory decays on later rounds");
memory.BeginRound();memory.Transit(3,new(1000,0,0));memory.Complete(2);
Check(memory.Risk(3,new(1000,0,0))==0,"defensive movement alone is not mislabeled as a death hotspot");
var attack=new RoundSpatialLearning();attack.BeginRound();attack.Transit(2,hot);attack.Death(2,hot);attack.Complete(3);
Check(attack.Risk(2,hot)>0&&attack.Risk(3,hot)==0,"failed attacking route credits only that side's own observations");
float failed=attack.Risk(2,hot);attack.BeginRound();attack.Transit(2,hot);attack.Complete(2);
Check(attack.Risk(2,hot)<failed*.65f,"successful reuse reduces the old route penalty beyond forgetting alone");
attack.BeginRound();attack.Death(2,new(float.NaN,0,0));attack.Complete(0);
Check(attack.Risk(2,new(float.NaN,0,0))==0,"invalid outcomes and positions cannot corrupt learning");
var limit=new RoundSpatialLearning();limit.BeginRound();for(int i=0;i<10000;i++)limit.Death(3,new(i*321,0,0));limit.Complete(2);
Check(limit.Regions<=512&&limit.Risk(3,Vector3.Zero)<=1,"region storage and scores remain bounded");
limit.Clear();Check(limit.Regions==0&&limit.LearnedRounds==0,"map reset clears learning without touching behavior parameters");
NavigationArea Node(int id,float x,float y,params int[] neighbors)=>new(){Id=id,Position=[x,y,0],Neighbors=neighbors,
 Corners=[[x-10,y-10,0],[x+10,y-10,0],[x+10,y+10,0],[x-10,y+10,0]]};
var graph=new TeamNavigationGraph([Node(0,0,0,1,2),Node(1,400,350,3),Node(2,400,-350,4),Node(3,800,350,5),Node(4,800,-350,5),Node(5,1200,0)]);
var baseline=graph.Path(0,5)!;var learned=new RoundSpatialLearning();learned.BeginRound();learned.Death(2,graph.Areas[baseline[1]].Point);learned.Complete(3);
var risks=graph.Areas.ToDictionary(p=>p.Key,p=>learned.Risk(2,p.Value.Point));
var changed=graph.DiversifiedPath(0,5,new Dictionary<int,int>(),risks)!;
Check(changed[1]!=baseline[1],"next round can actually change corridors after an attacking failure");
Check(graph.Length(changed)<=graph.Length(baseline)*1.4f+64,"learning cannot override the existing detour bound");
Check(graph.DiversifiedPath(0,5,new Dictionary<int,int>(),null)!.SequenceEqual(baseline),"exploration or disabled learning retains the original planner");
var winning=new RoundSpatialLearning();winning.BeginRound();winning.Death(3,hot);winning.Complete(3);
var losing=new RoundSpatialLearning();losing.BeginRound();losing.Death(3,hot);losing.Complete(2);
Check(losing.Risk(3,hot)>winning.Risk(3,hot),"lost rounds reinforce failures more strongly than costly wins");
var sideChange=new RoundSpatialLearning();sideChange.BeginRound(10,3);sideChange.Death(3,hot);sideChange.Complete(2);
sideChange.BeginRound(10,2);
Check(sideChange.Regions==0&&sideChange.LearnedRounds==0,"side swap cannot transfer the old opponents' role memory to a new team");
var lineups=new[]{(Id:"cold",Landing:new Vector3(3000,3000,0)),(Id:"hot",Landing:hot)};
Check(losing.Prioritize(3,lineups,g=>g.Landing,false)[0].Id=="hot","a lost defense actually changes existing lineup ordering next round");
Check(losing.Prioritize(3,lineups,g=>g.Landing,true)[0].Id=="cold","utility exploration retains the original lineup order");
Check(losing.Prioritize(2,lineups,g=>g.Landing,false)[0].Id=="cold","other team's lineups cannot use defensive casualty memory");
Console.WriteLine($"{checks} learning checks passed");
